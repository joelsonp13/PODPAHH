  async function loadCartAddresses() {
    var user = loggedUser();
    var token = getSessionToken();
    if (!user || !token || !window.PodpahhDB || !window.PodpahhDB.getAddresses) {
      cachedAddresses = [];
      selectedAddressId = null;
      renderCartAddressSection();
      return;
    }
    try {
      var res = await window.PodpahhDB.getAddresses(token);
      if (res && res.success) {
        cachedAddresses = res.data || [];
        var def = cachedAddresses.find(function(a) { return a.is_default; }) || cachedAddresses[0];
        if (!selectedAddressId && def) {
          selectedAddressId = def.id;
        } else if (selectedAddressId && !cachedAddresses.some(function(a) { return a.id === selectedAddressId; })) {
          selectedAddressId = def ? def.id : null;
        }
      } else {
        cachedAddresses = [];
        selectedAddressId = null;
      }
    } catch (e) {
      cachedAddresses = [];
      selectedAddressId = null;
    }
    renderCartAddressSection();
  }

