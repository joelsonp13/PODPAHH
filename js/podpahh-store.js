  window.vsSaveAddressFromCart = async function(e) {
    if (e) e.preventDefault();
    var form = $('#cartAddressForm');
    if (!form) return;
    var token = getSessionToken();
    if (!token) {
      alert('Faça login para salvar o endereço.');
      window.location.href = base() + '/pages/minha-conta.html';
      return;
    }
    var data = {
      label: form.label ? form.label.value.trim() : 'Casa',
      recipient_name: form.recipient_name ? form.recipient_name.value.trim() : '',
      phone: form.phone ? form.phone.value.trim() : '',
      postal_code: form.postal_code ? form.postal_code.value.trim() : '',
      street: form.street ? form.street.value.trim() : '',
      number: form.number ? form.number.value.trim() : '',
      complement: form.complement ? form.complement.value.trim() : '',
      neighborhood: form.neighborhood ? form.neighborhood.value.trim() : '',
      city: form.city ? form.city.value.trim() : '',
      state: form.state ? form.state.value.trim() : '',
      is_default: true
    };
    if (!data.recipient_name || !data.phone || !data.postal_code || !data.street || !data.number || !data.neighborhood || !data.city || !data.state) {
      alert('Por favor, preencha todos os campos obrigatórios do endereço.');
      return;
    }
    try {
      var res = await window.PodpahhDB.saveAddress(data, token);
      if (!res || !res.success) {
        alert(res && res.error ? res.error : 'Erro ao salvar endereço.');
        return;
      }
      selectedAddressId = res.data.id;
      form.reset();
      window.vsToggleAddressForm(false);
      await loadCartAddresses();
    } catch (err) {
      alert('Erro de conexão ao salvar endereço.');
    }
  };

