    lines.push('');
    lines.push('🏠 Endereço de entrega:');
    if (addr) {
      lines.push('Destinatário: ' + addr.recipient_name);
      lines.push('Tel: ' + formatPhoneBR(addr.phone));
      lines.push('CEP: ' + addr.postal_code);
      lines.push('Endereço: ' + addr.street + ', ' + addr.number + (addr.complement ? ' (' + addr.complement + ')' : ''));
      lines.push('Bairro: ' + addr.neighborhood + ' — ' + addr.city + '/' + addr.state);
      if (addr.label) lines.push('Rótulo: ' + addr.label);
    } else {
      lines.push('— (Nenhum endereço selecionado)');
    }
    lines.push('');
    lines.push('💳 Forma de pagamento: (responder: PIX ou Cartão)');
    lines.push('');
    lines.push('Olá! Quero finalizar este pedido. Podem confirmar? ✅');
