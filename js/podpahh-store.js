  function wireSearch() {
    $$('form[role="search"]').forEach(function (f) {
      f.addEventListener('submit', function (e) {
        e.preventDefault();
        var inp = $('input[name="s"], input[type="search"], input', f);
        var q = inp ? inp.value.trim() : '';
        var base = (document.body.getAttribute('data-base') || '.');
        window.location.href = base + '/pages/loja.html' + (q ? '?q=' + encodeURIComponent(q) : '');
      });
    });
    // filtro client-side na loja
    var params = new URLSearchParams(location.search);
    var q = (params.get('q') || '').toLowerCase();
    if (q && $$('.pcard').length) {
      $$('.pcard').forEach(function (card) {
        var nameEl = $('.pcard-name', card);
        var name = nameEl ? nameEl.textContent.toLowerCase() : '';
        var li = card.closest('li') || card;
        if (name.indexOf(q) === -1) li.style.display = 'none';
      });
    }
  }

  /* ---------------- LAZY LOAD (data-src → src) ---------------- */
  function lazyImages() {
    var PH = (function () { try { return base() + '/assets/images/placeholder.svg'; } catch (e) { return ''; } })();
    var imgs = $$('.pcard img[data-src], img[data-src]');
    if (!('IntersectionObserver' in window)) {
      imgs.forEach(function (im) { im.src = url(im.getAttribute('data-src')); });
      return;
    }
    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (en) {
        if (!en.isIntersecting) return;
        var im = en.target;
        var ds = im.getAttribute('data-src');
        if (ds) {
          im.onerror = function () { im.onerror = null; if (PH) im.src = PH; };
          im.src = url(ds);
        }
        var dss = im.getAttribute('data-srcset');
        if (dss) im.setAttribute('srcset', dss);
        im.removeAttribute('data-src');
        io.unobserve(im);
      });
    }, { rootMargin: '300px' });
    imgs.forEach(function (im) { io.observe(im); });
  }

  /* ---------------- BROKEN IMAGE FALLBACK ---------------- */
  function fallbackBroken() {
    var PH = (function () { try { return base() + '/assets/images/placeholder.svg'; } catch (e) { return ''; } })();
    if (!PH) return;
    document.addEventListener('error', function (e) {
      if (e.target.tagName === 'IMG' && e.target.src && !e.target.src.endsWith('placeholder.svg')) {
        e.target.onerror = null;
        e.target.src = PH;
      }
    }, true);
  }

