  function syncWishButtons() {
    var wish;
    try { wish = JSON.parse(localStorage.getItem(CFG.wishKey)) || {}; }
    catch (e) { wish = {}; }
    $$('.pcard-wish[onclick]').forEach(function (btn) {
      var m = (btn.getAttribute('onclick') || '').match(/vsToggleWish\((\d+)/);
      if (m && wish[m[1]]) btn.classList.add('on');
    });
  }

  /* ---------------- DRAWER RENDER ---------------- */
  function renderDrawer() {
    var items = $('#cartPanelItems'); if (!items) return;
    var cart = loadCart(), cat = loadCatalog();
    var keys = Object.keys(cart);
    var footer = $('#cartPanelFooter');
    if (!keys.length) {
      items.innerHTML = '<div class="cart-empty"><i class="fa fa-shopping-cart"></i><p>Seu carrinho está vazio</p></div>';
      if (footer) footer.style.display = 'none';
      return;
    }
    var html = '<div class="cart-items-header"><span>Produto</span><span>Preço</span><span>Qtd</span><span>Total</span><span></span></div>';
    keys.forEach(function (k) {
      var p = cat[k]; if (!p) return;
      var it = cart[k];
      html += '<div class="cart-item-row">' +
        '<div class="cart-item-product">' +
        '<img src="' + esc(url(p.img)) + '" alt="' + esc(p.name) + '" loading="lazy" style="width:52px;height:52px;object-fit:cover;border-radius:8px">' +
        '<span class="cip-name">' + esc(p.name) + '</span>' +
        '</div>' +
        '<div class="cart-item-price">' + money(p.price) + '</div>' +
        '<div class="cart-item-qty">' +
        '<button class="ci-qty-btn" onclick="vsQty(\'' + safeId(k) + '\',-1)">−</button>' +
        '<span class="ci-qty-val">' + it.qty + '</span>' +
        '<button class="ci-qty-btn" onclick="vsQty(\'' + safeId(k) + '\',1)">+</button>' +
        '</div>' +
        '<div class="cart-item-subtotal">' + money(p.price * it.qty) + '</div>' +
        '<div class="cart-item-remove"><button class="ci-remove" onclick="vsRemoveItem(\'' + safeId(k) + '\')" title="Remover"><i class="fa fa-trash"></i></button></div>' +
        '</div>';
    });
    items.innerHTML = html;
    var sub = cartSubtotal(cart);
    var el;
    if ((el = $('#cpSubtotal'))) el.textContent = money(sub);
    if ((el = $('#cpTotal'))) el.textContent = money(sub);
    if (footer) footer.style.display = '';
  }

