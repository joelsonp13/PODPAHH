  /* ---------------- LAZY LOAD (data-src → src) ---------------- */
  function lazyImages() {
    var PH = (function () { try { return base() + '/assets/images/placeholder.svg'; } catch (e) { return ''; } })();
    var imgs = $$('.pcard img[data-src], img[data-src]');
    if (!('IntersectionObserver' in window)) {
      imgs.forEach(function (im) { im.src = url(im.getAttribute('data-src')); });
      return;
    }
    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (en) {
        if (!en.isIntersecting) return;
        var im = en.target;
        var ds = im.getAttribute('data-src');
        if (ds) {
          im.onerror = function () { im.onerror = null; if (PH) im.src = PH; };
          im.src = url(ds);
        }
        var dss = im.getAttribute('data-srcset');
        if (dss) im.setAttribute('srcset', dss);
        im.removeAttribute('data-src');
        io.unobserve(im);
      });
    }, { rootMargin: '300px' });
    imgs.forEach(function (im) { io.observe(im); });
  }

  /* ---------------- BROKEN IMAGE FALLBACK ---------------- */
  function fallbackBroken() {
    var PH = (function () { try { return base() + '/assets/images/placeholder.svg'; } catch (e) { return ''; } })();
    if (!PH) return;
    document.addEventListener('error', function (e) {
      if (e.target.tagName === 'IMG' && e.target.src && !e.target.src.endsWith('placeholder.svg')) {
        e.target.onerror = null;
        e.target.src = PH;
      }
    }, true);
  }

  /* ---------------- ADMIN PRODUCTS SYNC (server local / Supabase) ---------------- */
  function syncAdminProducts() {
    // Rota pública: só produtos com estoque, sem dados sensíveis de clientes/admin
    fetch('/api/public/products')
      .then(function (r) { return r.json(); })
      .then(function (json) {
        if (!json.success || !json.data || !json.data.length) return;
        var map = {};
        var byId = {};
        json.data.forEach(function (p) {
          var pid = p.source_id || p.id; // produtos importados mantêm o ID original do catálogo
          map[pid] = {
            name: p.name,
            price: p.price,
            img: p.image || '',
            url: p.url || '',
            category: p.category
          };
          byId[pid] = p;
        });
        // Re-registra modelos já salvos no carrinho (chaves pid__mid) para
        // o drawer/página do carrinho exibi-los mesmo após recarregar.
        try {
          ['podpahh_cart_v2', 'podpahh_cart_v1'].forEach(function (ck) {
            var cart = {};
            try { cart = JSON.parse(localStorage.getItem(ck)) || {}; } catch (e) { cart = {}; }
            Object.keys(cart).forEach(function (key) {
              if (map[key]) return;
              var sep = key.lastIndexOf('__');
              if (sep < 0) return;
              var p = byId[key.substring(0, sep)];
              if (!p) return;
              var found = null;
              (p.models || []).forEach(function (x) { if (key === (p.source_id || p.id) + '__' + x.id) found = x; });
              if (!found) return;
              var mp = Number(found.price) || 0;
              map[key] = {
                name: p.name + ' — ' + found.name,
                price: mp > 0 ? mp : p.price,
                img: found.image || p.image || '',
                url: '', category: p.category
              };
            });
          });
        } catch (e) {}
        window.PODPAHH_ADMIN_PRODUCTS = map;
        renderAll(); // re-renderiza carrinho/badges com preços atualizados do banco
      })
      .catch(function () { /* servidor offline: segue com catálogo estático */ });
  }

