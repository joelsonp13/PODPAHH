  // WhatsApp válido: 10 ou 11 dígitos, DDD 11-99 (11 dígitos = celular com 9)
  function validCustomerPhone(v) {
    var d = String(v || '').replace(/\D/g, '');
    if (d.length !== 10 && d.length !== 11) return '';
    var ddd = parseInt(d.substring(0, 2), 10);
    if (ddd < 11 || ddd > 99) return '';
    if (d.length === 11 && d[2] !== '9') return '';
    return d;
  }

  function loginRedirect(msg) {
    if (msg) alert(msg);
    window.location.href = base() + '/pages/minha-conta.html';
  }

  function buildOrderMessage() {
    var cart = loadCart(), cat = loadCatalog();
    var user = loggedUser();
    var lines = [];
    lines.push('*NOVO PEDIDO — PODPAHH* 🛒');
    lines.push('—————————————');
    var sub = 0, totalItems = 0;
    Object.keys(cart).forEach(function (k) {
      var p = cat[k]; if (!p) return;
      var tot = p.price * cart[k].qty;
      sub += tot; totalItems += cart[k].qty;
      lines.push('▪ *' + p.name + '*');
      lines.push('   ' + cart[k].qty + 'x ' + money(p.price) + ' = *' + money(tot) + '*');
    });
    lines.push('—————————————');
    lines.push('📦 Total de itens: ' + totalItems);
    lines.push('Total: *' + money(sub) + '*');
    lines.push('—————————————');
    // Dados do cliente VÊM do cadastro — preenchidos automaticamente, sem perguntar de novo
    lines.push('*DADOS DO CLIENTE (cadastro)*');
    lines.push('👤 Nome: ' + ((user && user.name) || '—'));
    lines.push('📱 WhatsApp: ' + ((user && user.phone) ? formatPhoneBR(user.phone) : '—'));
    lines.push((user && user.email) ? ('✉️ E-mail: ' + user.email) : '✉️ E-mail: —');
    lines.push('');
    lines.push('🏠 Endereço de entrega:');
    if (window.__podpahh_selected_address_text) {
      lines.push(window.__podpahh_selected_address_text.split('\n').map(l => l ? '   ' + l : l).join('\n'));
    } else {
      lines.push('   [endereço não selecionado — pedido bloqueado]');
    }
    lines.push('💳 Forma de pagamento: (responder: PIX ou Cartão)');
    lines.push('');
    lines.push('Olá! Quero finalizar este pedido. Podem confirmar? ✅');
    return lines.join('\n');
  }

  // Formata (41) 99999-9999 para exibir na mensagem
  function formatPhoneBR(digits) {
    var d = String(digits || '').replace(/\D/g, '');
    if (d.length === 11) return '(' + d.substring(0, 2) + ') ' + d.substring(2, 7) + '-' + d.substring(7);
    if (d.length === 10) return '(' + d.substring(0, 2) + ') ' + d.substring(2, 6) + '-' + d.substring(6);
    return d;
  }

  function checkoutUrl() {
    // encodeURIComponent só do texto; número limpo, só dígitos
    return 'https://wa.me/' + waNumber + '?text=' + encodeURIComponent(buildOrderMessage());
  }

