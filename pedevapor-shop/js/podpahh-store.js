  function formatAddressText(a) {
    if (!a) return '';
    var l = [];
    l.push('   ' + (a.street || '') + ', ' + (a.number || '') + (a.complement ? ' - ' + a.complement : ''));
    l.push('   ' + (a.neighborhood || '') + ' — ' + (a.city || '') + '/' + (a.state || ''));
    l.push('   CEP ' + String(a.postal_code || '').replace(/^(\d{5})(\d{3})$/, '$1-$2'));
    if (a.recipient_name) l.push('   Receber: ' + a.recipient_name + (a.phone ? ' (' + formatPhoneBR(a.phone) + ')' : ''));
    return l.filter(Boolean).join('\n');
  }

  // Extrai dígitos de qualquer string
  function onlyDigits(s) { return String(s || '').replace(/\D/g, ''); }

  // Máscara CEP: 12345-678
  function maskCep(v) {
    var d = onlyDigits(v).substring(0, 8);
    return d.length > 5 ? d.substring(0, 5) + '-' + d.substring(5) : d;
  }

  // Máscara telefone BR: (41) 99999-9999
  function maskPhoneBR(v) {
    var d = onlyDigits(v).substring(0, 11);
    if (d.length <= 2) return d;
    if (d.length <= 6) return '(' + d.substring(0, 2) + ') ' + d.substring(2);
    if (d.length <= 10) return '(' + d.substring(0, 2) + ') ' + d.substring(2, 6) + '-' + d.substring(6);
    return '(' + d.substring(0, 2) + ') ' + d.substring(2, 7) + '-' + d.substring(7);
  }

  // Preenche cidade/estado automaticamente via ViaCEP
  function viacepLookup(cepDigits) {
    return fetch('https://viacep.com.br/ws/' + cepDigits + '/json/')
      .then(function (r) { return r.json(); })
      .catch(function () { return null; });
  }

